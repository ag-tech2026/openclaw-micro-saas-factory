function buildLandingPages() {
  console.log('\n🏗️  Building landing pages from configs...\n');

  if (!fs.existsSync(CONFIGS_DIR)) {
    console.error(`❌ Configs directory not found: ${CONFIGS_DIR}`);
    console.log('Create it with: mkdir landing-configs');
    process.exit(1);
  }

  const files = fs.readdirSync(CONFIGS_DIR).filter((f) => {
    const ext = path.extname(f);
    return ['.json', '.yaml', '.yml'].includes(ext);
  });

  if (files.length === 0) {
    console.log('⚠️  No config files found in landing-configs/');
    return;
  }

  let jsonConfigs = 0;
  let yamlConfigs = 0;

  files.forEach((file) => {
    const ext = path.extname(file);
    const slug = getSlugFromFilename(file);
    const filePath = path.join(CONFIGS_DIR, file);

    try {
      let config: any;

      if (ext === '.json') {
        jsonConfigs++;
        const content = fs.readFileSync(filePath, 'utf-8');
        config = JSON.parse(content);
      } else {
        yamlConfigs++;
        // Only import yaml if needed
        const yaml = require('js-yaml');
        const content = fs.readFileSync(filePath, 'utf-8');
        config = yaml.load(content);
      }

      // Validate with zod-like checks (simplified for build script)
      if (!config.slug || !config.name) {
        console.warn(`⚠️  Skipping ${file}: missing required fields (slug, name)`);
        return;
      }

      // Ensure slug matches filename
      if (config.slug !== slug) {
        console.warn(`⚠️  ${file}: slug "${config.slug}" doesn't match filename. Using "${slug}"`);
      }

      // Create output directory
      const outputDir = path.join(GENERATED_DIR, slug);
      fs.mkdirSync(outputDir, { recursive: true });

      // Generate page
      const pageContent = generateDynamicRoutePage(slug, config);
      fs.writeFileSync(path.join(outputDir, 'page.tsx'), pageContent);

      console.log(`✅ Generated: /product/${slug}`);
    } catch (error: any) {
      console.error(`❌ Error processing ${file}:`, error.message);
    }
  });

  console.log(`\n📊 Summary:`);
  console.log(`   JSON configs: ${jsonConfigs}`);
  console.log(`   YAML configs: ${yamlConfigs}`);
  console.log(`   Total pages generated: ${jsonConfigs + yamlConfigs}`);
  console.log('\n✅ Build complete!\n');
}

// Run build
buildLandingPages();
