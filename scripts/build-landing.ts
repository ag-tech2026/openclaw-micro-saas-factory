#!/usr/bin/env node

/**
 * Build script for generating static Next.js pages from landing configs
 * Run with: npm run build:landing
 */

import fs from 'fs';
import path from 'path';

const CONFIGS_DIR = path.join(process.cwd(), 'landing-configs');
const GENERATED_DIR = path.join(process.cwd(), 'src', 'app', 'product');

function getSlugFromFilename(filename: string): string {
  const ext = path.extname(filename);
  return path.basename(filename, ext);
}

